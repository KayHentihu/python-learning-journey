for i in range(1, 11): # break untuk menghentikan loop secara langsung
    if i == 5:
        break
    print(i)
    
for i in range(1, 6): # continue untuk melewati satu putaran dan lanjut ke putaran berikutnya.
    if i == 3:
        continue
    print(i)
    
