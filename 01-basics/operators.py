a = 10
b = 3

# 4 operator dasar
print(a + b) # cetak penjumlahan a dan b
print(a - b) # cetak pengurangan a dan b
print(a * b) # cetak perkalian a dan b
print(a / b) # cetak pembagian a dan b

# 3 operator yang menarik
print(10 % 3) # cetak sisa bagi 10 dan 3
print(10 // 3) # cetak pembagian bulat kebawah
print(10 ** 3) # cetak 10^3

# Comparison Operator
a = 10
b = 5

print(a > b)
print(a < b)
print(a == b)
print(a != b)
print(a >= b)
print(a <= b)